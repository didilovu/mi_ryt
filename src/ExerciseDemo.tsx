export function ExerciseDemo({
  exercise,
  compact = false,
}: {
  exercise: Exercise;
  compact?: boolean;
}) {
  const [playing, setPlaying] = useState(true);
  return (
    <div
      className={`demo ${compact ? "compact" : ""} ${playing ? "playing" : ""}`}
    >
      <div className="frames">
        {exercise.poses.map((key, i) => {
          const p = poses[key];
          return (
            <figure key={key} className={`frame frame-${i}`}>
              <svg
                viewBox="0 0 200 170"
                role="img"
                aria-label={`${exercise.name}: ${exercise.captions[i]}`}
              >
                <ellipse
                  cx="100"
                  cy="154"
                  rx="77"
                  ry="5"
                  fill="#D9C8F2"
                  opacity=".4"
                />
                {p.slice(2).map((points, j) => (
                  <polyline
                    key={j}
                    points={points as string}
                    fill="none"
                    stroke={j % 2 ? "#82709B" : "#45414D"}
                    strokeWidth="6"
                    strokeLinecap="round"
                    strokeLinejoin="round"
                  />
                ))}
                <circle
                  cx={p[0]}
                  cy={p[1]}
                  r="11"
                  fill="#F4C7D9"
                  stroke="#45414D"
                  strokeWidth="3"
                />
              </svg>
              <figcaption>
                <span>{i + 1}</span> {exercise.captions[i]}
              </figcaption>
            </figure>
          );
        })}
      </div>
      <button
        className="text-button demo-control"
        onClick={() => setPlaying(!playing)}
      >
        {playing ? <Pause size={15} /> : <Play size={15} />}{" "}
        {playing ? "Остановить показ" : "Продолжить показ"}
      </button>
      <small>
        {exercise.id === "plank"
          ? "Локти под плечами · предплечья лежат на полу"
          : exercise.id === "child"
            ? "Таз у пяток · лоб и вытянутые руки на полу"
            : "Схемы последовательности · чередуйте стороны"}
      </small>
    </div>
  );
}
