export function workoutForWeek(
  id: string,
  week: number,
  rest: number,
): Workout {
  const base = workouts.find((w) => w.id === id)!;
  const steps =
    id === "circuit"
      ? [
          warm,
          ...Array.from({ length: [3, 4, 5, 5][week - 1] }, () =>
            ["jack", "squat", "knees", "climber", "side"].map((e) =>
              timed(e, 40, 20),
            ),
          ).flat(),
          cool,
          breath,
        ]
      : base.steps.map((s) => ({ ...s }));
  return {
    ...base,
    steps: steps.map((s) => ({
      ...s,
      sets: week === 1 && s.sets > 2 ? 2 : s.sets,
      seconds:
        s.seconds && week === 3 && s.sets > 1 ? s.seconds + 5 : s.seconds,
      rest: id === "circuit" ? s.rest : s.rest === 45 ? rest : s.rest,
    })),
  };
}
export function plannedSeconds(w: Workout) {
  return (
    w.steps.reduce(
      (n, s) => n + s.sets * (s.seconds ?? s.estimate ?? 0) + s.sets * s.rest,
      0,
    ) - (w.steps.at(-1)?.rest ?? 0)
  );
}
